    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        if (!validarCampos()) {
            return;
        }

        boolean ok = controller.insertarPartido(
                txtEquipoLocal.getText().trim(),
                txtEquipovisitante.getText().trim(),
                parseFecha(),
                txtEstadio.getText().trim(),
                txtCiudad.getText().trim(),
                Integer.parseInt(txtCapacidad.getText().trim()),
                (String) cmbEstado.getSelectedItem()
        );

        if (ok) {
            JOptionPane.showMessageDialog(this, "Partido registrado correctamente.");
            limpiarCampos();
            cargarTabla(controller.listarPartidos());
        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo registrar el partido."
                            + "Verifica que los equipos no sean iguales.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }


    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:

        int fila = jTable1.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Selecciona un partido de la tabla primero.");
            return;
        }
        if (!validarCampos()) {
            return;
        }

        int id = (int) jTable1.getValueAt(fila, 0);
        boolean ok = controller.actualizarPartido(
                id,
                txtEquipoLocal.getText().trim(),
                txtEquipovisitante.getText().trim(),
                parseFecha(),
                txtEstadio.getText().trim(),
                txtCiudad.getText().trim(),
                Integer.parseInt(txtCapacidad.getText().trim()),
                (String) cmbEstado.getSelectedItem()
        );

        if (ok) {
            JOptionPane.showMessageDialog(this, "Partido actualizado correctamente.");
            limpiarCampos();
            cargarTabla(controller.listarPartidos());
        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo actualizar el partido.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:

        int fila = jTable1.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Selecciona un partido de la tabla primero.");
            return;
        }

        int id = (int) jTable1.getValueAt(fila, 0);
        int confirm = JOptionPane.showConfirmDialog(this,
                "¿Deseas cancelar este partido?"
                        + "Se cambiara su estado a cancelado.",
                "Confirmar cancelación", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            boolean ok = controller.eliminarPartido(id);
            if (ok) {
                JOptionPane.showMessageDialog(this, "Partido cancelado correctamente.");
                limpiarCampos();
                cargarTabla(controller.listarPartidos());
            } else {
                JOptionPane.showMessageDialog(this,
                        "No se pudo cancelar el partido."
                                + "Posiblemente ya esta cancelado.",
                        "Error", JOptionPane.ERROR_MESSAGE);
            }
        }

    }//GEN-LAST:event_btnEliminarActionPerformed

