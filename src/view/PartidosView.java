    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:

        String texto = txtBuscar.getText().trim();

        if (texto.isEmpty()) {
            // Si está vacío muestra todos
            cargarTabla(controller.listarPartidos());
            return;
        }

        try {
            // busca por id si es numeraso
            int id = Integer.parseInt(texto);
            PartidoModel p = controller.buscarPorId(id);
            if (p != null) {
                java.util.List<PartidoModel> lista = new java.util.ArrayList<>();
                lista.add(p);
                cargarTabla(lista);
            } else {
                JOptionPane.showMessageDialog(this, "No se enconto partido con ID: " + id);
            }
        } catch (NumberFormatException e) {
            // Si no es número → busca por equipo (usa ILIKE del SP)
            java.util.List<PartidoModel> lista = controller.buscarPorEquipo(texto);
            if (lista.isEmpty()) {
                JOptionPane.showMessageDialog(this, "No se encontraron partidos con: " + texto);
            } else {
                cargarTabla(lista);
            }
        }

    }//GEN-LAST:event_btnBuscarActionPerformed

