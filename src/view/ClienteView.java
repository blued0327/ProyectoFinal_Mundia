    private void btnModificarClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarClienteActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();
    if (fila < 0) {
        JOptionPane.showMessageDialog(this, "Selecciona un cliente de la tabla primero.");
        return;
    }
    
    int id = (int) jTable1.getValueAt(fila, 0);
    controller.actualizarCliente(
        id,
        txtNombre.getText(),
        txtApellido.getText(),
        txtTelefono.getText(),
        txtEmail.getText(),
        txtDireccion.getText()
    );
    JOptionPane.showMessageDialog(this, "Cliente actualizado correctamente.");
    limpiarCampos();
    cargarTabla(controller.obtenerClientes());
    }//GEN-LAST:event_btnModificarClienteActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String texto = txtBuscar.getText().trim();
    
    if (texto.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Escribe un nombre o ID para buscar.");
        return;
    }
    
    try {
        // Si es número → busca por ID
        int id = Integer.parseInt(texto);
        ClienteModel cm = controller.buscarPorId(id);
        
        if (cm != null) {
            java.util.List<ClienteModel> lista = new java.util.ArrayList<>();
            lista.add(cm);
            cargarTabla(lista);
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró cliente con ID: " + id);
        }
        
    } catch (NumberFormatException e) {
        // Si no es número → busca por nombre
        java.util.List<ClienteModel> lista = controller.buscarPorNombre(texto);
        
        if (lista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No se encontraron clientes con: " + texto);
        } else {
            cargarTabla(lista);
        }
    }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();
    if (fila < 0) {
        JOptionPane.showMessageDialog(this, "Selecciona un cliente de la tabla primero.");
        return;
    }
    
    int id = (int) jTable1.getValueAt(fila, 0);
    int confirm = JOptionPane.showConfirmDialog(this, 
        "¿Deseas desactivar este cliente?", "Confirmar", JOptionPane.YES_NO_OPTION);
    
    if (confirm == JOptionPane.YES_OPTION) {
        controller.cambiarEstado(id);
        JOptionPane.showMessageDialog(this, "Cliente desactivado.");
        cargarTabla(controller.obtenerClientes());
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

