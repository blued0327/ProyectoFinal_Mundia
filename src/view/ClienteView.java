    private void cargarTabla(java.util.List<ClienteModel> lista) {
    javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
        new String[]{"ID", "Nombre", "Apellido", "Telefono", "Email", "Direccion"}, 0) {
        public boolean isCellEditable(int row, int col) { return false; }
    };
    for (ClienteModel cm : lista) {
        modelo.addRow(new Object[]{
            cm.getId(), cm.getNombre(), cm.getApellido(),
            cm.getTelefono(), cm.getEmail(), cm.getDireccion()
        });
    }
    jTable1.setModel(modelo);
}

